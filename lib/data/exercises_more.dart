Exercise _x(
  String name,
  List<String> primary,
  List<String> secondary,
  String equipment,
  String description, [
  String loadMode = 'external',
]) {
  final (low, high) = defaultRepRange(equipment: equipment, primary: primary, secondary: secondary);
  return Exercise(
    name: name,
    primary: primary,
    secondary: secondary,
    equipment: equipment,
    description: description,
    loadMode: loadMode,
    repMin: low,
    repMax: high,
  );
}

